-- 009 · procurement
--
-- Phase B increment 1. Until now there was no answer to "where did this stock
-- come from?". The ledger (003) recorded that stock ARRIVED — reason 'receipt' —
-- but never from whom, at what cost, or against what order. A receipt with no
-- purchase order behind it is an assertion, not a record.
--
-- ── WHAT THIS BUYS, AND THE DISTINCTION THE SCHEMA TURNS ON ───────────────
--
-- Two kinds of thing are purchased, and conflating them is the mistake this
-- schema exists to prevent:
--
--   * PRODUCT — a real inventory item. Receiving one MUST write a ledger row,
--     because there are now more of them on the shelf than there were.
--
--   * MATERIAL — a finish code ('Natural Oak', 'Brushed Brass'). It is a
--     swatch a customer picks for a worktop, not a board in a rack. It has no
--     price, no unit and no quantity on hand; `materials` in this codebase is
--     (id, json) with fields applicableTo/brightness/category/image/name and
--     nothing else. Receiving one must NEVER touch stock, because inventing a
--     quantity for a colour is exactly how a system starts reporting inventory
--     that does not exist.
--
-- So `purchase_order_lines.item_kind` is not cosmetic: it decides whether a
-- goods receipt moves stock. The application branches on it, and the exit test
-- asserts both directions — a product receipt moves stock exactly once, a
-- material receipt moves it never.
--
-- ── WHY stock_movements IS NOT ALTERED ────────────────────────────────────
--
-- Adding an inventory dimension to the ledger (so products and materials share
-- one table) would mean changing a table that is already applied in production,
-- and D-04 makes applied migrations immutable. It is also unnecessary: the
-- ledger is product-only by design (003), and a finish code has no quantity to
-- ledger. The two are joined by `ref_type='goods_receipt'`, not by a shared
-- dimension.
--
-- ── QUANTITIES ARE INTEGERS ───────────────────────────────────────────────
--
-- applyStockMovement() rejects a non-integer delta, and it is the only legal
-- write path to stock. A NUMERIC/REAL qty_ordered would therefore be unable to
-- reach the ledger without silent rounding, so quantities are whole units here
-- and the constraint is honest about it. Money is REAL/DOUBLE PRECISION, which
-- is the same convention as products.price in the base schema.
--
-- ── THE IDEMPOTENCY GAP THIS CLOSES ───────────────────────────────────────
--
-- 003 shipped a partial unique index covering reason='sale' only, so a retried
-- sale could not double-decrement. Receiving had no equivalent, so a retried
-- goods receipt would double-count stock — the receiving twin of the
-- overselling bug. See uq_stock_movements_receipt_ref below.

/* ─────────────────────────── suppliers ─────────────────────────── */

CREATE TABLE IF NOT EXISTS suppliers(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          TEXT   NOT NULL UNIQUE,
  name          TEXT   NOT NULL,
  contact_name  TEXT,
  phone         TEXT,
  email         TEXT,
  address       TEXT,
  /* NTN/VAT. Deliberately free text: the format is jurisdiction-specific, and
     the specification forbids hard-coding business data that should be
     configurable. A CHECK here would encode one country's rules into a schema
     that has to serve another. */
  tax_ref       TEXT,
  payment_terms TEXT,
  currency      TEXT   NOT NULL DEFAULT 'PKR',
  active        INTEGER NOT NULL DEFAULT 1,
  notes         TEXT,
  created_at    TEXT   NOT NULL,
  updated_at    TEXT   NOT NULL,
  CONSTRAINT suppliers_code_nonempty CHECK (length(trim(code)) > 0),
  CONSTRAINT suppliers_name_nonempty CHECK (length(trim(name)) > 0),
  CONSTRAINT suppliers_active_boolean CHECK (active IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_suppliers_active ON suppliers(active, name);

/* ──────────────────────── purchase orders ────────────────────────
   State machine: draft → approved → sent → partially_received → received,
   with cancelled reachable from any state that has not been fully received.

   'partially_received' is a real state, not a derived flag, because goods
   arrive in instalments and "how much of this order is still outstanding" is
   the question purchasing asks every morning. */

CREATE TABLE IF NOT EXISTS purchase_orders(
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref         TEXT   NOT NULL UNIQUE,
  supplier_id BIGINT NOT NULL,
  status      TEXT   NOT NULL DEFAULT 'draft',
  currency    TEXT   NOT NULL DEFAULT 'PKR',
  expected_at TEXT,
  approved_by TEXT,
  approved_at TEXT,
  sent_at     TEXT,
  closed_at   TEXT,
  note        TEXT,
  created_by  TEXT,
  created_at  TEXT   NOT NULL,
  updated_at  TEXT   NOT NULL,
  CONSTRAINT po_status_known CHECK (status IN (
    'draft','approved','sent','partially_received','received','cancelled')),
  /* An order cannot leave draft without an approval behind it. Cancelling a
     draft is the one legitimate exit, and 'cancelled' stays permitted so a
     mis-created order does not have to be approved first in order to be
     buried. */
  CONSTRAINT po_approved_before_issue CHECK (
    status IN ('draft','cancelled') OR approved_at IS NOT NULL),
  CONSTRAINT po_supplier_fkey FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_purchase_orders_supplier ON purchase_orders(supplier_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_status   ON purchase_orders(status, id DESC);

CREATE TABLE IF NOT EXISTS purchase_order_lines(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id BIGINT  NOT NULL,
  line_no           INTEGER NOT NULL,
  item_kind         TEXT    NOT NULL,
  item_id           TEXT    NOT NULL,
  description       TEXT,
  qty_ordered       INTEGER NOT NULL,
  unit              TEXT,
  unit_cost         DOUBLE PRECISION NOT NULL DEFAULT 0,
  CONSTRAINT pol_kind_known CHECK (item_kind IN ('product','material')),
  CONSTRAINT pol_qty_positive CHECK (qty_ordered > 0),
  CONSTRAINT pol_cost_non_negative CHECK (unit_cost >= 0),
  CONSTRAINT pol_line_unique UNIQUE (purchase_order_id, line_no),
  /* One row per item per order. TWO LINES FOR THE SAME PRODUCT ON ONE ORDER
     would make the receipt idempotency index below ambiguous — the second
     receipt of that product in the same GRN would violate it for a legitimate
     reason. Forbidding the shape instead of weakening the index is the right
     trade: raise the quantity, or raise a second order. */
  CONSTRAINT pol_item_unique UNIQUE (purchase_order_id, item_kind, item_id),
  /* NO foreign key on item_id: it references products OR materials depending
     on item_kind, so no single FK can be correct. The same trade-off as
     audit_logs.actor_id, with the same consequence — the application enforces
     it, and a deleted product leaves a legible historical line rather than
     cascading it away. */
  CONSTRAINT pol_po_fkey FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_purchase_order_lines_po ON purchase_order_lines(purchase_order_id, line_no);

/* ──────────────────────── goods receipts ────────────────────────
   A receipt is a document: one delivery, many lines. It is separate from the
   order because goods arrive over time and each arrival needs its own
   timestamp, its own receiver and its own reference for the supplier's delivery
   note. */

CREATE TABLE IF NOT EXISTS goods_receipts(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref               TEXT   NOT NULL UNIQUE,
  purchase_order_id BIGINT NOT NULL,
  received_at       TEXT   NOT NULL,
  received_by       TEXT,
  note              TEXT,
  created_at        TEXT   NOT NULL,
  CONSTRAINT gr_po_fkey FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_goods_receipts_po ON goods_receipts(purchase_order_id, id DESC);

CREATE TABLE IF NOT EXISTS goods_receipt_lines(
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  goods_receipt_id       BIGINT  NOT NULL,
  purchase_order_line_id BIGINT  NOT NULL,
  qty_received           INTEGER NOT NULL,
  CONSTRAINT grl_qty_positive CHECK (qty_received > 0),
  CONSTRAINT grl_line_unique UNIQUE (goods_receipt_id, purchase_order_line_id),
  CONSTRAINT grl_receipt_fkey FOREIGN KEY (goods_receipt_id) REFERENCES goods_receipts(id) ON DELETE CASCADE,
  CONSTRAINT grl_line_fkey FOREIGN KEY (purchase_order_line_id) REFERENCES purchase_order_lines(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_goods_receipt_lines_line ON goods_receipt_lines(purchase_order_line_id);

/* THE GUARD THIS MODULE NEEDS.

   003's uq_stock_movements_sale_ref covers reason='sale'. Receiving had no
   equivalent, so a retried POST would write a second +N and the shelf would
   silently gain stock that never arrived.

   The predicate is deliberately narrow on BOTH axes:

     reason = 'receipt'        — sales and adjustments are unaffected.
     ref_type = 'goods_receipt' — 003 seeds opening balances as reason
                                  'receipt' with ref_type NULL, and
                                  POST /api/products writes an opening balance
                                  the same way. A broader predicate would
                                  collide with those and break production
                                  seeding on a second product.

   Shipping the narrow index is what makes it safe to add to a live database. */
CREATE UNIQUE INDEX IF NOT EXISTS uq_stock_movements_receipt_ref
  ON stock_movements(ref_type, ref_id, product_id)
  WHERE reason = 'receipt' AND ref_type = 'goods_receipt' AND ref_id IS NOT NULL;

/* ────────────────────────── purchasing role ──────────────────────────
   002:176 hard-codes the role vocabulary, so a purchasing role needs the
   constraint replaced rather than added. Tested afterwards: an unknown role
   must still be rejected (test-integrity asserts exactly that with 'emperor').

   Idempotent on the constraint's TEXT, not merely its existence — re-running
   must converge on the new vocabulary rather than conclude "already present". */

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
      JOIN pg_class t     ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE c.contype = 'c' AND t.relname = 'users'
       AND c.conname = 'users_role_known' AND n.nspname = current_schema()
       AND pg_get_constraintdef(c.oid) LIKE '%purchasing%'
  ) THEN
    ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_known;
    ALTER TABLE users ADD CONSTRAINT users_role_known
      CHECK ("role" IN ('owner','editor','sales','finance','purchasing','viewer'));
  END IF;
END $$;
