-- 003 · stock movement ledger
--
-- Before this, stock was a single mutable integer on the product row. It had no
-- history: you could not answer "why is this 47?", could not attribute a
-- shortage to an order, and could not reconcile a physical count.
--
-- It was worse than that. Nothing decremented it either. POST /api/orders
-- checked `stock_qty` and then never reduced it, so a product with 99 units
-- could be sold an unlimited number of times. The check that made checkout look
-- responsible was decorative.
--
-- Design, from 03-DATA-AND-TENANCY.md §3:
--
--   * INSERT-only. There is no UPDATE and no DELETE path. Corrections are
--     compensating rows, so the history of a mistake is part of the history.
--
--   * `products.stock_qty` becomes a DERIVED CACHE over SUM(delta) rather than
--     the source of truth. A test recomputes it and fails on any disagreement,
--     so drift is caught rather than trusted.
--
--   * Reasons are a closed set. An unenumerated reason means somebody bypassed
--     the helper, which is exactly what this is meant to make visible.
--
--   * `reserved` is NOT a movement. A reservation is a claim on available
--     stock, not a change to it; recording it as a delta would make stock look
--     sold before it shipped. Reservations live in their own table.
--
-- Keys are (product_id, id) on the ledger: the common query is "the recent
-- movements for this product", and ordering by insertion is the natural axis.
--
-- No warehouse_id yet. There is one warehouse today (Lahore); adding a nullable
-- column later is cheap, whereas inventing a warehouse table now and migrating
-- every row into a single fake warehouse is not. When a second location lands,
-- it arrives with backfill and a default — see 003's sibling in Phase C.

CREATE TABLE IF NOT EXISTS stock_movements(
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  TEXT   NOT NULL,
  delta       INTEGER NOT NULL,
  reason      TEXT   NOT NULL,
  ref_type    TEXT,
  ref_id      BIGINT,
  note        TEXT,
  created_by  TEXT,
  created_at  TEXT   NOT NULL,
  CONSTRAINT stock_movements_delta_nonzero   CHECK (delta <> 0),
  CONSTRAINT stock_movements_reason_known    CHECK (reason IN (
    'receipt','sale','return','adjustment','transfer','wastage'
  )),
  CONSTRAINT stock_movements_product_fkey    FOREIGN KEY (product_id)
    REFERENCES products(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_stock_movements_product ON stock_movements(product_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_stock_movements_ref     ON stock_movements(ref_type, ref_id);

-- One sale must not be recorded twice. The helper is idempotent by design, but a
-- second guard at the storage layer means a retried request cannot silently
-- double-decrement the catalogue.
CREATE UNIQUE INDEX IF NOT EXISTS uq_stock_movements_sale_ref
  ON stock_movements(ref_type, ref_id, product_id)
  WHERE reason = 'sale' AND ref_type IS NOT NULL AND ref_id IS NOT NULL;

/* Reservations: claims on available stock that are not movements yet.
   A cart that has not been paid for should not reduce stock — but it should
   stop the same units being promised twice. */
CREATE TABLE IF NOT EXISTS stock_reservations(
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  TEXT   NOT NULL,
  qty         INTEGER NOT NULL,
  ref_type    TEXT   NOT NULL,
  ref_id      BIGINT,
  status      TEXT   NOT NULL DEFAULT 'held',
  expires_at  TEXT,
  created_at  TEXT   NOT NULL,
  CONSTRAINT stock_reservations_qty_positive CHECK (qty > 0),
  CONSTRAINT stock_reservations_status_known CHECK (status IN ('held','released','consumed')),
  CONSTRAINT stock_reservations_product_fkey FOREIGN KEY (product_id)
    REFERENCES products(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_stock_reservations_product
  ON stock_reservations(product_id, status);
CREATE INDEX IF NOT EXISTS idx_stock_reservations_ref
  ON stock_reservations(ref_type, ref_id);

/* Opening balance. Existing stock was set by hand or by the seed; without an
   opening row, every product would reconcile as a discrepancy on day one and
   the reconciliation test would be noise. This records what was on the shelf
   when the ledger started — once, and only for products that have no movements
   yet, so re-running the migration cannot double-count. */
INSERT INTO stock_movements(product_id, delta, reason, note, created_by, created_at)
SELECT p.id, p.stock_qty, 'receipt', 'opening balance at ledger introduction', 'migration:003', '2026-11-08T00:00:00.000Z'
  FROM products p
 WHERE NOT EXISTS (SELECT 1 FROM stock_movements m WHERE m.product_id = p.id)
   AND p.stock_qty <> 0;
