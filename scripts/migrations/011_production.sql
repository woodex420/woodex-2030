-- 011 · production: bills of materials, job cards, material consumption
--
-- Phase B increment 3. Procurement buys material and receiving puts it on the
-- shelf; nothing yet consumes it. Until this migration the ledger could only
-- grow. A factory that can receive but not issue has an inventory report, not
-- a production system.
--
-- ── WHY THE LEDGER NEEDED A NEW REASON ────────────────────────────────────
--
-- 003 closed `stock_movements.reason` to
--   ('receipt','sale','return','adjustment','transfer','wastage')
-- and none of those honestly describes "these components went into a desk".
-- Filing production under 'adjustment' would hide real consumption inside the
-- bucket reserved for corrections, and the whole point of a closed vocabulary
-- is that a reader can trust it.
--
-- 003 is applied in production and D-04 makes applied migrations immutable, so
-- the CHECK is replaced here rather than edited there — the same pattern 009
-- used for the role vocabulary.
--
-- ── WHY A JOB CARD NAMES WHAT IT BUILDS ───────────────────────────────────
--
-- The obvious design is "a sales order is confirmed, therefore explode its
-- BOM". That is not possible with the data that exists: `orders.items` is a
-- JSON array of {name, price, qty} with NO product id, on every order. A line
-- that says "BALLMER Executive Desk" cannot be resolved to a products row
-- without fuzzy-matching a display name, which is exactly how the wrong thing
-- gets built.
--
-- So a job card states its product_id and qty explicitly, and carries the
-- order id as context for the shop floor. Deriving consumption automatically
-- from a sales order needs order creation to persist product ids — a separate
-- change to the sales path, recorded as open rather than faked here.
--
-- ── WHAT IS CONSUMED, AND WHAT IS NOT ─────────────────────────────────────
--
-- A BOM line is a `product` or a `material`, mirroring procurement:
--
--   product   real inventory, so issuing it writes a NEGATIVE ledger row
--   material  a finish code (Natural Oak); no quantity on hand, so issuing it
--             records that it was used and moves NO stock
--
-- Getting that backwards either invents inventory for a colour or silently
-- fails to consume a real component.

/* ───────────────────────── bills of materials ───────────────────────── */

CREATE TABLE IF NOT EXISTS boms(
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref         TEXT   NOT NULL UNIQUE,
  product_id  TEXT   NOT NULL,
  name        TEXT   NOT NULL,
  version     INTEGER NOT NULL DEFAULT 1,
  /* Output per run: a BOM for a desk that yields 2 units per build is real in
     upholstery and cabinetry, and baking "always 1" into the schema would force
     a workaround later. */
  output_qty  INTEGER NOT NULL DEFAULT 1,
  active      INTEGER NOT NULL DEFAULT 1,
  notes       TEXT,
  created_at  TEXT   NOT NULL,
  updated_at  TEXT   NOT NULL,
  CONSTRAINT bom_version_positive CHECK (version >= 1),
  CONSTRAINT bom_output_positive  CHECK (output_qty > 0),
  CONSTRAINT bom_active_boolean   CHECK (active IN (0, 1)),
  CONSTRAINT bom_product_fkey FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT
);

/* One active BOM per product. Superseding a BOM deactivates the old row rather
   than deleting it: job cards already built against version 1 must keep
   pointing at the recipe they were built to. */
CREATE UNIQUE INDEX IF NOT EXISTS uq_boms_active_product
  ON boms(product_id) WHERE active = 1;

CREATE INDEX IF NOT EXISTS idx_boms_product ON boms(product_id, version DESC);

CREATE TABLE IF NOT EXISTS bom_lines(
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bom_id         BIGINT  NOT NULL,
  line_no        INTEGER NOT NULL,
  item_kind      TEXT    NOT NULL,
  item_id        TEXT    NOT NULL,
  qty_per_output INTEGER NOT NULL,
  unit           TEXT,
  note           TEXT,
  CONSTRAINT boml_kind_known CHECK (item_kind IN ('product','material')),
  CONSTRAINT boml_qty_positive CHECK (qty_per_output > 0),
  CONSTRAINT boml_line_unique UNIQUE (bom_id, line_no),
  /* No FK on item_id: it references products OR materials by item_kind, so no
     single FK is correct — the same trade-off as purchase_order_lines. */
  CONSTRAINT boml_bom_fkey FOREIGN KEY (bom_id) REFERENCES boms(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_bom_lines_bom ON bom_lines(bom_id, line_no);

/* ───────────────────────────── job cards ─────────────────────────────
   queued → in_progress → qc → done, with cancelled reachable until done.

   `qc` is a stage, not a flag, because work genuinely waits there. 'done' is
   unreachable without qc_passed_at: shipping un-inspected work is the failure
   the QC gate exists to prevent, and a boolean somebody can flip is not a gate. */

CREATE TABLE IF NOT EXISTS job_cards(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref           TEXT   NOT NULL UNIQUE,
  bom_id        BIGINT,
  product_id    TEXT   NOT NULL,
  order_id      BIGINT,
  qty_to_build  INTEGER NOT NULL,
  qty_built     INTEGER NOT NULL DEFAULT 0,
  stage         TEXT   NOT NULL DEFAULT 'queued',
  assigned_to   TEXT,
  started_at    TEXT,
  completed_at  TEXT,
  qc_passed_at  TEXT,
  qc_by         TEXT,
  qc_note       TEXT,
  due_at        TEXT,
  notes         TEXT,
  created_by    TEXT,
  created_at    TEXT   NOT NULL,
  updated_at    TEXT   NOT NULL,
  CONSTRAINT jc_stage_known CHECK (stage IN ('queued','in_progress','qc','done','cancelled')),
  CONSTRAINT jc_qty_positive CHECK (qty_to_build > 0),
  CONSTRAINT jc_qty_built_sane CHECK (qty_built >= 0 AND qty_built <= qty_to_build),
  CONSTRAINT jc_done_requires_qc CHECK (stage <> 'done' OR qc_passed_at IS NOT NULL),
  /* The BOM is nullable: a one-off job may be built without a stored recipe.
     The product is NOT nullable — a job card that does not say what it builds
     cannot post output stock. */
  CONSTRAINT jc_product_fkey FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT,
  CONSTRAINT jc_bom_fkey FOREIGN KEY (bom_id) REFERENCES boms(id) ON DELETE RESTRICT,
  CONSTRAINT jc_order_fkey FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_job_cards_stage   ON job_cards(stage, id DESC);
CREATE INDEX IF NOT EXISTS idx_job_cards_order   ON job_cards(order_id);
CREATE INDEX IF NOT EXISTS idx_job_cards_product ON job_cards(product_id);

/* What this job card must consume, and what it actually has.
   Each row owns exactly one ledger movement, which is what makes issuing
   idempotent: ref_type='job_card_material', ref_id=<this row's id>. */
CREATE TABLE IF NOT EXISTS job_card_materials(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_card_id       BIGINT  NOT NULL,
  line_no           INTEGER NOT NULL,
  item_kind         TEXT    NOT NULL,
  item_id           TEXT    NOT NULL,
  qty_required      INTEGER NOT NULL,
  qty_issued        INTEGER NOT NULL DEFAULT 0,
  created_at        TEXT    NOT NULL,
  CONSTRAINT jcm_kind_known CHECK (item_kind IN ('product','material')),
  CONSTRAINT jcm_required_positive CHECK (qty_required > 0),
  CONSTRAINT jcm_issued_sane CHECK (qty_issued >= 0 AND qty_issued <= qty_required),
  CONSTRAINT jcm_line_unique UNIQUE (job_card_id, line_no),
  CONSTRAINT jcm_item_unique UNIQUE (job_card_id, item_kind, item_id),
  CONSTRAINT jcm_job_fkey FOREIGN KEY (job_card_id) REFERENCES job_cards(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_jcm_job ON job_card_materials(job_card_id, line_no);

/* THE ISSUE GUARD. A retried "issue materials" would decrement stock twice —
   the production twin of the double-receipt bug 009 closed.

   It cannot be keyed on (ref_type, ref_id) the way the 009 receipt guard is.
   A receipt row is final: one receipt line, one movement. A material line is
   NOT final — a foreman who has 10 of the 40 brackets must be able to record
   that and top up later, which is two movements for one line. A unique row per
   line would reject the top-up.

   So issues are keyed on the CUMULATIVE quantity the line reaches, not on the
   delta. "Take this line to 20 issued" is a statement about state: replaying
   it lands on 20 again, collides, and is refused. Taking it to 30 afterwards is
   a different key and is allowed, because it is genuinely different work.
   Idempotency by construction, not by trusting the caller to reuse a token. */
ALTER TABLE stock_movements ADD COLUMN IF NOT EXISTS idem_key TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_stock_movements_idem_key
  ON stock_movements(ref_type, idem_key)
  WHERE idem_key IS NOT NULL;

/* The OUTPUT movement needs no key: one job card yields output once, so
   (ref_type, ref_id) is already unique and a retried completion collides. */

CREATE UNIQUE INDEX IF NOT EXISTS uq_stock_movements_production_output
  ON stock_movements(ref_type, ref_id, product_id)
  WHERE reason = 'production' AND ref_type = 'job_card_output' AND ref_id IS NOT NULL;

/* ─────────────────── the stock reason vocabulary ───────────────────
   'production' joins the closed set. Idempotent on the constraint TEXT, not
   merely its existence, so re-running converges rather than concluding
   "already present" from an older definition. */

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
      JOIN pg_class t     ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE c.contype = 'c' AND t.relname = 'stock_movements'
       AND c.conname = 'stock_movements_reason_known' AND n.nspname = current_schema()
       AND pg_get_constraintdef(c.oid) LIKE '%production%'
  ) THEN
    ALTER TABLE stock_movements DROP CONSTRAINT IF EXISTS stock_movements_reason_known;
    ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_reason_known
      CHECK (reason IN ('receipt','sale','return','adjustment','transfer','wastage','production'));
  END IF;
END $$;

/* ───────────────────────── the production role ─────────────────────────
   The shop floor needs to issue materials and move job cards without being
   able to edit the catalogue, record payments, or raise purchase orders. */

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
      JOIN pg_class t     ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE c.contype = 'c' AND t.relname = 'users'
       AND c.conname = 'users_role_known' AND n.nspname = current_schema()
       AND pg_get_constraintdef(c.oid) LIKE '%production%'
  ) THEN
    ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_known;
    ALTER TABLE users ADD CONSTRAINT users_role_known
      CHECK ("role" IN ('owner','editor','sales','finance','purchasing','production','viewer'));
  END IF;
END $$;
