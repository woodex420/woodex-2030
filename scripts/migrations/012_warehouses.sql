-- 012 · inventory depth: warehouses, storage locations, transfer orders,
--       and a stock reservation that actually reserves something
--
-- Phase 7 increment 1. 003 built the ledger and 009–011 gave it sources and
-- sinks: buy, receive, issue into a build. What the system still cannot say is
-- *where* a thing is. A single `products.stock_qty` is the whole world, so the
-- first question a warehouse manager asks — "which of the three godowns has it"
-- — has no answer.
--
-- ── WHY A WAREHOUSE IS NOT A LOCATION ────────────────────────────────────
--
-- They are different granularities and both are asked about. "How much teak in
-- Lahore" is a warehouse question; "which rack" is a location question. Collaps-
-- ing them forces one of the two into a naming convention inside a free-text
-- field, which is how stock gets lost. warehouse → location is a real parent-
-- child relation, and a location's warehouse is the only thing that decides the
-- warehouse a movement belongs to — never a second, separately-supplied value
-- that can disagree.
--
-- ── WHY MOVEMENTS GAIN A LOCATION, AND WHY IT IS NULLABLE ────────────────
--
-- History is not backfillable. Every existing stock_movements row was recorded
-- when "where" was not a question the system could ask, and inventing a default
-- location for them would assert something false about the past: that someone
-- put those units on that rack. NULL means "recorded before location was
-- tracked", which is true.
--
-- Going forward the API requires a location on every movement it writes. The
-- asymmetry is deliberate and one-directional: old rows are honest about not
-- knowing, new rows are never allowed not to say.
--
-- ── WHY THE BALANCE TABLE IS A PROJECTION, NOT A SOURCE ──────────────────
--
-- stock_levels(product, location) holds qty. It is NOT authoritative. The ledger
-- is. This is the same discipline 003 established for products.stock_qty, and
-- for the same reason: two writable copies of one number diverge the moment a
-- write path forgets. The difference here is that a projection has to be
-- *rebuildable*, so this migration adds an endpoint contract (see the reconcile
-- route) that recomputes every level from the ledger and reports drift the way
-- /api/stock-movements/reconcile already does for the product total.
--
-- Sum of a product's stock_levels must equal its stock_qty. That invariant is
-- what makes the extra table safe rather than a new source of lies, and it is
-- asserted in the test suite, not assumed.

/* ───────────────────────────── warehouses ───────────────────────────── */

CREATE TABLE IF NOT EXISTS warehouses(
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        TEXT   NOT NULL UNIQUE,
  name        TEXT   NOT NULL,
  /* Free text, not an enum: a second city is an ordinary Tuesday and a CHECK
     against a list of cities is a migration every time the business grows. */
  city        TEXT,
  address     TEXT,
  manager     TEXT,
  phone       TEXT,
  /* Exactly one warehouse should be the default destination when a movement
     does not name one. Enforced by a partial unique index below rather than by
     application convention — two defaults is a bug that silently picks a winner. */
  is_default  INTEGER NOT NULL DEFAULT 0,
  active      INTEGER NOT NULL DEFAULT 1,
  notes       TEXT,
  created_at  TEXT   NOT NULL,
  updated_at  TEXT   NOT NULL,
  CONSTRAINT warehouses_code_not_blank CHECK (length(trim(code)) > 0),
  CONSTRAINT warehouses_name_not_blank CHECK (length(trim(name)) > 0),
  /* Named explicitly. An unnamed CHECK still exists, but PostgreSQL names it
     `<table>_<column>_check`, which the drift audit cannot match against the
     migration text — the audit would then under-declare and the self-test that
     proves it can fail would itself fail. Every constraint in this repo carries
     its own name for that reason. */
  CONSTRAINT warehouses_is_default_boolean CHECK (is_default IN (0, 1)),
  CONSTRAINT warehouses_active_boolean CHECK (active IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_warehouses_single_default
  ON warehouses(is_default) WHERE is_default = 1;

/* ───────────────────────── storage locations ───────────────────────── */

CREATE TABLE IF NOT EXISTS storage_locations(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  warehouse_id  BIGINT NOT NULL,
  code          TEXT   NOT NULL,
  name          TEXT   NOT NULL,
  /* aisle/rack/bin as one field: real sites use all three, some use none, and
     three nullable columns would be mostly empty in every deployment. */
  zone          TEXT,
  active        INTEGER NOT NULL DEFAULT 1,
  notes         TEXT,
  created_at    TEXT   NOT NULL,
  updated_at    TEXT   NOT NULL,
  CONSTRAINT storage_locations_warehouse_fkey FOREIGN KEY (warehouse_id)
    REFERENCES warehouses(id) ON DELETE RESTRICT,
  CONSTRAINT storage_locations_warehouse_code_uniq UNIQUE (warehouse_id, code),
  CONSTRAINT storage_locations_code_not_blank CHECK (length(trim(code)) > 0),
  CONSTRAINT storage_locations_active_boolean CHECK (active IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_storage_locations_warehouse
  ON storage_locations(warehouse_id, active);

/* ─────────── stock movements: the location that was written ───────────
   Nullable on purpose — see the header. No default, because a default would
   be exactly the false claim this column exists to avoid. */

ALTER TABLE stock_movements ADD COLUMN IF NOT EXISTS location_id BIGINT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
      JOIN pg_class t     ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE c.contype = 'f' AND t.relname = 'stock_movements'
       AND c.conname = 'stock_movements_location_fkey' AND n.nspname = current_schema()
  ) THEN
    ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_location_fkey
      FOREIGN KEY (location_id) REFERENCES storage_locations(id) ON DELETE RESTRICT;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_stock_movements_location
  ON stock_movements(location_id, id DESC);

/* ───────────────────── stock levels (projection) ───────────────────── */

CREATE TABLE IF NOT EXISTS stock_levels(
  product_id   TEXT   NOT NULL,
  location_id  BIGINT NOT NULL,
  qty          INTEGER NOT NULL DEFAULT 0,
  updated_at   TEXT   NOT NULL,
  CONSTRAINT stock_levels_pkey PRIMARY KEY (product_id, location_id),
  CONSTRAINT stock_levels_product_fkey FOREIGN KEY (product_id)
    REFERENCES products(id) ON DELETE CASCADE,
  CONSTRAINT stock_levels_location_fkey FOREIGN KEY (location_id)
    REFERENCES storage_locations(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_stock_levels_location
  ON stock_levels(location_id);

/* ───────────────────────── stock transfers ─────────────────────────
   Moving units between locations is two ledger entries, never one edit.
   A single row with a "from" and a "to" column would mean the ledger could not
   answer "what is at this location" without special-casing transfers. Instead:
   -qty at the source, +qty at the destination, both reason 'transfer', both
   pointing at one transfer id. The pair is the record; the transfer row is the
   document that ties them together.

   status exists because a real transfer is dispatched and then received, and
   the gap between those is when goods are in a truck and belong to neither
   location. 'in_transit' is the honest third state; a system that only has
   done/not-done has to lie about that window. */

CREATE TABLE IF NOT EXISTS stock_transfers(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref               TEXT   NOT NULL UNIQUE,
  from_location_id  BIGINT NOT NULL,
  to_location_id    BIGINT NOT NULL,
  status            TEXT   NOT NULL DEFAULT 'draft',
  note              TEXT,
  created_by        TEXT,
  dispatched_at     TEXT,
  received_at       TEXT,
  created_at        TEXT   NOT NULL,
  updated_at        TEXT   NOT NULL,
  CONSTRAINT stock_transfers_from_fkey FOREIGN KEY (from_location_id)
    REFERENCES storage_locations(id) ON DELETE RESTRICT,
  CONSTRAINT stock_transfers_to_fkey FOREIGN KEY (to_location_id)
    REFERENCES storage_locations(id) ON DELETE RESTRICT,
  CONSTRAINT stock_transfers_status_known
    CHECK (status IN ('draft','dispatched','received','cancelled')),
  /* A transfer to where it already is moves nothing while writing two ledger
     rows that sum to zero, which looks like activity in every report. */
  CONSTRAINT stock_transfers_distinct_locations
    CHECK (from_location_id <> to_location_id),
  /* Dispatch is the moment stock leaves. It cannot have been dispatched before
     it was created, and cannot be received before it was dispatched. */
  CONSTRAINT stock_transfers_received_needs_dispatch
    CHECK (received_at IS NULL OR dispatched_at IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_stock_transfers_status
  ON stock_transfers(status, created_at DESC);

CREATE TABLE IF NOT EXISTS stock_transfer_lines(
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transfer_id  BIGINT NOT NULL,
  product_id   TEXT   NOT NULL,
  qty          INTEGER NOT NULL,
  CONSTRAINT stock_transfer_lines_transfer_fkey FOREIGN KEY (transfer_id)
    REFERENCES stock_transfers(id) ON DELETE CASCADE,
  CONSTRAINT stock_transfer_lines_product_fkey FOREIGN KEY (product_id)
    REFERENCES products(id) ON DELETE RESTRICT,
  CONSTRAINT stock_transfer_lines_qty_positive CHECK (qty > 0),
  CONSTRAINT stock_transfer_lines_uniq UNIQUE (transfer_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_stock_transfer_lines_transfer
  ON stock_transfer_lines(transfer_id);

/* ───────────── reservations: 003's table, finally usable ─────────────
   003 created stock_reservations and nothing ever wrote to it — no route, no
   test, no caller. A table nothing uses is not a feature; it is a promise that
   was never kept, and it misleads anyone reading the schema into believing
   soft allocation exists.

   Two properties have to hold for a reservation to mean anything:
     1. Holding qty does not change stock_qty. A reservation is a claim on
        future availability, not a movement; if it decremented stock, cancelling
        an order would have to reconstruct a number that was never subtracted.
     2. Available = on hand − held, and a caller must not be able to reserve
        more than is available. That check needs to see every live hold for the
        product, so the status vocabulary and an index over it are added here.
   003 shipped the columns but the status CHECK allowed 'held','released',
   'consumed'; that vocabulary is kept exactly — it is already correct — and
   what is added is the constraint that a hold must belong to a product that
   exists and point at something. */

/* 003 already declared stock_reservations_product_fkey, so 012 does NOT add it
   again. Re-adding "if not exists" would be a no-op at runtime but would count
   as a second declaration when the integrity suite derives its expected FK
   total from these files — the suite would then demand 54 constraints and find
   53, which reads as a missing foreign key and is really a duplicated promise.
   The reservation changes 012 actually needs follow. */

/* A hold with no expiry is a hold forever: an abandoned cart would reserve
   stock permanently with nobody to notice. The column is added but left
   nullable — history has no expiry and cannot be given one. */
ALTER TABLE stock_reservations ADD COLUMN IF NOT EXISTS released_at TEXT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
      JOIN pg_class t     ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE c.contype = 'c' AND t.relname = 'stock_reservations'
       AND c.conname = 'stock_reservations_ref_required' AND n.nspname = current_schema()
  ) THEN
    /* A hold that does not say what it is holding stock FOR cannot be released
       when that thing goes away, so it leaks. */
    ALTER TABLE stock_reservations ADD CONSTRAINT stock_reservations_ref_required
      CHECK (ref_type IS NOT NULL AND length(trim(ref_type)) > 0);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_stock_reservations_live
  ON stock_reservations(product_id, status) WHERE status = 'held';
