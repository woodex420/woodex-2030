-- 010 · supplier invoices and three-way matching
--
-- The missing third leg. A purchase order says what was ordered, a goods
-- receipt says what arrived, and a supplier invoice says what is being charged.
-- Without the third, receiving is a warehouse exercise with no financial
-- consequence — you cannot answer "did we pay for what we received?".
--
-- ── WHY A NEW TABLE RATHER THAN invoices ──────────────────────────────────
--
-- The obvious move is to add a supplier_id to `invoices` and a direction
-- column. That is wrong here, and the PRD says why: Phase 1 finance is
-- receivables (customer invoice, what they owe us); Phase 2 introduces vendors
-- and payables (supplier invoice, what we owe them). The two share a word and
-- almost nothing else:
--
--   invoices                          supplier_invoices
--   ─────────────────────────         ──────────────────────────
--   customer TEXT (a name)            supplier_id (a real counterparty)
--   quote_id / order_id               purchase_order_id / goods_receipt_id
--   paid  (money in)                  paid  (money out)
--   status Issued→Paid                status Draft→Posted→Paid→Cancelled
--   balance = total - paid            balance = total - paid  (payable)
--
-- Merging them would mean every receivables query growing an
-- `AND direction='out'` filter, and one missed filter reports a payable as
-- revenue. Separate tables cost a join and cannot be got wrong silently.
--
-- ── WHAT MATCHING MEANS HERE ──────────────────────────────────────────────
--
-- Three-way match compares, per line: ordered (PO) vs received (GRN) vs billed
-- (this invoice). The verdict is stored on the invoice, together with the
-- numbers that produced it, because "matched" with no figures behind it is not
-- evidence — it is a claim.
--
-- A tolerance exists because freight and rounding legitimately differ from the
-- order. It is read from meta['procurement.match_tolerance'] rather than
-- hard-coded: a configurable business rule belongs in configuration.
--
--   matched    every line billed ≤ received ≤ ordered, total within tolerance
--   tolerance  a difference exists but is within the configured tolerance
--   variance   a difference exceeds it — review required before payment
--
-- Matching never blocks recording an invoice. A supplier's bill is a fact that
-- arrives whether or not it agrees with us; refusing to record it would just
-- move the argument to a spreadsheet. It blocks PAYMENT instead.

CREATE TABLE IF NOT EXISTS supplier_invoices(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref               TEXT   NOT NULL UNIQUE,
  supplier_id       BIGINT NOT NULL,
  purchase_order_id BIGINT,
  goods_receipt_id  BIGINT,
  /* The supplier's OWN document number. Kept verbatim because that is what
     appears on their statement, their reminder and their lawyer's letter. */
  supplier_ref      TEXT   NOT NULL,
  invoice_date      TEXT   NOT NULL,
  due_date          TEXT,
  currency          TEXT   NOT NULL DEFAULT 'PKR',
  subtotal          DOUBLE PRECISION NOT NULL DEFAULT 0,
  tax               DOUBLE PRECISION NOT NULL DEFAULT 0,
  total             DOUBLE PRECISION NOT NULL DEFAULT 0,
  paid              DOUBLE PRECISION NOT NULL DEFAULT 0,
  status            TEXT   NOT NULL DEFAULT 'draft',
  match_state       TEXT,
  match_json        TEXT,
  matched_at        TEXT,
  note              TEXT,
  created_by        TEXT,
  created_at        TEXT   NOT NULL,
  updated_at        TEXT   NOT NULL,
  CONSTRAINT si_status_known CHECK (status IN ('draft','posted','paid','cancelled')),
  CONSTRAINT si_match_known  CHECK (match_state IS NULL OR match_state IN ('matched','tolerance','variance','unlinked')),
  CONSTRAINT si_total_non_negative CHECK (total >= 0),
  CONSTRAINT si_paid_non_negative  CHECK (paid >= 0),
  /* A payable cannot be over-settled. The receivables side does NOT enforce
     this (POST /api/invoices/:id/payments sets paid = paid + amount with no
     ceiling), which is a real bug there but not one to copy into the ledger
     that writes money outward. */
  CONSTRAINT si_paid_within_total CHECK (paid <= total + 0.005),
  /* A posted invoice must have been matched at some point — 'unlinked' counts
     as a recorded verdict (no PO to match against), not as never checked. */
  CONSTRAINT si_posted_has_match CHECK (status = 'draft' OR match_state IS NOT NULL),
  CONSTRAINT si_supplier_fkey FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE RESTRICT,
  /* RESTRICT, not SET NULL: a payables row whose order vanished is an orphan
     nobody can chase. The order must be dealt with, not detached. */
  CONSTRAINT si_po_fkey FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id) ON DELETE RESTRICT,
  CONSTRAINT si_grn_fkey FOREIGN KEY (goods_receipt_id) REFERENCES goods_receipts(id) ON DELETE RESTRICT
);

/* THE DUPLICATE-BILL GUARD.
   Paying the same supplier invoice twice is the single most common accounts-
   payable fraud and it is usually a clerical accident, not a scheme: the same
   document scanned in twice, or entered by two people on the same morning.
   The supplier's own reference is the only identifier they will quote back, so
   uniqueness is per supplier rather than global — two suppliers may legitimately
   both have an invoice numbered 1001. */
CREATE UNIQUE INDEX IF NOT EXISTS uq_supplier_invoices_supplier_ref
  ON supplier_invoices(supplier_id, supplier_ref);

CREATE INDEX IF NOT EXISTS idx_supplier_invoices_po     ON supplier_invoices(purchase_order_id);
CREATE INDEX IF NOT EXISTS idx_supplier_invoices_status ON supplier_invoices(status, id DESC);

CREATE TABLE IF NOT EXISTS supplier_invoice_lines(
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_invoice_id    BIGINT  NOT NULL,
  purchase_order_line_id BIGINT,
  line_no                INTEGER NOT NULL,
  description            TEXT,
  qty_billed             INTEGER NOT NULL,
  unit_cost              DOUBLE PRECISION NOT NULL DEFAULT 0,
  line_total             DOUBLE PRECISION NOT NULL DEFAULT 0,
  CONSTRAINT sil_qty_positive CHECK (qty_billed > 0),
  CONSTRAINT sil_cost_non_negative CHECK (unit_cost >= 0),
  CONSTRAINT sil_total_non_negative CHECK (line_total >= 0),
  CONSTRAINT sil_line_unique UNIQUE (supplier_invoice_id, line_no),
  /* One bill line per PO line per invoice. Two lines against the same PO line
     would make "how much of this line have we been billed for" ambiguous, which
     is exactly the question matching exists to answer. */
  CONSTRAINT sil_pol_unique UNIQUE (supplier_invoice_id, purchase_order_line_id),
  CONSTRAINT sil_invoice_fkey FOREIGN KEY (supplier_invoice_id) REFERENCES supplier_invoices(id) ON DELETE CASCADE,
  CONSTRAINT sil_pol_fkey FOREIGN KEY (purchase_order_line_id) REFERENCES purchase_order_lines(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_supplier_invoice_lines_invoice ON supplier_invoice_lines(supplier_invoice_id, line_no);
CREATE INDEX IF NOT EXISTS idx_supplier_invoice_lines_pol     ON supplier_invoice_lines(purchase_order_line_id);

/* Payments OUT. Mirrors `payments`, which records money in, and adds a
   ceiling the receivable side lacks. */
CREATE TABLE IF NOT EXISTS supplier_payments(
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_invoice_id BIGINT NOT NULL,
  amount              DOUBLE PRECISION NOT NULL,
  method              TEXT DEFAULT 'Bank transfer',
  reference           TEXT,
  note                TEXT,
  paid_at             TEXT,
  created_at          TEXT NOT NULL,
  CONSTRAINT sp_amount_positive CHECK (amount > 0),
  CONSTRAINT sp_invoice_fkey FOREIGN KEY (supplier_invoice_id) REFERENCES supplier_invoices(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_supplier_payments_invoice ON supplier_payments(supplier_invoice_id, id DESC);

/* Over-billing the same PO line, across invoices, is the mirror of over-
   receiving it. The application checks it inside the transaction; this index
   makes the simple case (one bill line per PO line globally unique) impossible
   to get wrong by hand. It is deliberately NOT global-unique — partial and
   staged invoicing is legitimate — so the application owns the sum check and
   this comment records why there is no index for it. */

/* Configurable tolerance, seeded but not forced: an installation that wants
   zero tolerance deletes this row and gets exact matching.

   Guarded on the table existing rather than assumed. `meta` is part of the base
   PostgreSQL schema, but a migration applied to a partially-built environment
   must not fail on a missing key-value table — the tolerance is a convenience,
   not a schema dependency, and the application defaults to 0 when the row is
   absent. */
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.tables
     WHERE table_name = 'meta' AND table_schema = current_schema()
  ) THEN
    INSERT INTO meta(key, value)
    SELECT 'procurement.match_tolerance', '0'
     WHERE NOT EXISTS (SELECT 1 FROM meta WHERE key = 'procurement.match_tolerance');
  END IF;
END $$;
