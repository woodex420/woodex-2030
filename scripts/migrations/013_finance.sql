-- 013 · finance depth: chart of accounts, an immutable double-entry journal,
--       credit notes, expenses, tax records, payment schedules
--
-- Phase 5's finance half. 010 gave the system what it owes and what it is owed
-- — supplier_invoices and invoices, each with payments against them. What it
-- cannot do is the one thing an accountant means by "the books":
--
--   state, for any account, what it holds and why, and prove the two add up.
--
-- ── WHY A JOURNAL AND NOT MORE COLUMNS ───────────────────────────────────
--
-- invoices and supplier_invoices are documents, not ledger entries. `paid` on
-- an invoice is a cached total maintained by a route; there is no record of
-- which account received the money, and adding an `account` column to payments
-- would still leave expenses, credit notes and tax on separate, differently
-- shaped tables that happen to contain amounts. Every report would then be a
-- UNION of five sources with five different notions of "when".
--
-- A journal entry flips that: every financial event becomes debit/credit lines
-- against named accounts, and one rule — debits equal credits — makes the whole
-- system checkable. Invoices keep their status caches; the journal is the
-- reason they are true.
--
-- ── IMMUTABILITY IS A MECHANISM, NOT A CONVENTION ────────────────────────
--
-- The spec asks for "immutable transaction history". An API that simply does
-- not expose an UPDATE for journal lines is not immutable: it is a policy that
-- holds until someone writes a route, runs a repair script, or opens psql.
-- So this migration installs database rules that refuse UPDATE and DELETE on
-- journal_lines outright. Corrections are posted, not edited: a reversing entry
-- has its own row, its own author and its own timestamp, and the original
-- remains visible. That is the difference between a ledger and a spreadsheet.
--
-- The guard is deliberately on the LINES and not on journal_entries' header
-- columns: a description typo is not a financial fact, and forbidding the
-- correction of prose would push people to delete and repost — the exact
-- behaviour this design exists to make unnecessary.

/* ───────────────────────────── accounts ─────────────────────────────
   A flat list with a `kind`, not a tree. Woodex does not need departmental
   sub-accounts; it needs "how much cash", "how much owed to us", "how much
   revenue", and the kinds are what make a trial balance readable without a
   chart-of-accounts editor nobody will maintain. A `parent_id` could be added
   later without rewriting anything here. */

CREATE TABLE IF NOT EXISTS accounts(
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         TEXT   NOT NULL UNIQUE,
  name         TEXT   NOT NULL,
  /* The five that exist. `kind` is what decides which side of the trial
     balance an account's normal balance sits on, so it cannot be free text. */
  kind         TEXT   NOT NULL,
  /* Assets and expenses are debit-normal; liabilities, equity and revenue are
     credit-normal. Storing the direction rather than deriving it from `kind`
     keeps the arithmetic explicit at the points that use it — a reader should
     not have to remember accounting conventions to check a sign. */
  active       INTEGER NOT NULL DEFAULT 1,
  notes        TEXT,
  created_at   TEXT   NOT NULL,
  updated_at   TEXT   NOT NULL,
  CONSTRAINT accounts_kind_known
    CHECK (kind IN ('asset','liability','equity','revenue','expense')),
  CONSTRAINT accounts_active_boolean CHECK (active IN (0, 1)),
  CONSTRAINT accounts_code_not_blank CHECK (length(trim(code)) > 0),
  CONSTRAINT accounts_name_not_blank CHECK (length(trim(name)) > 0)
);

/* ─────────────────────────── journal entries ───────────────────────────
   One document per financial event, carrying its lines. `source_type` +
   `source_id` say what caused it (invoice, payment, expense, credit_note),
   which is what makes "why is this in the books" answerable without reading
   six tables. Both are nullable because a manual entry has no source document
   and an opening balance has no event. */

CREATE TABLE IF NOT EXISTS journal_entries(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref           TEXT   NOT NULL UNIQUE,
  entry_date    TEXT   NOT NULL,
  memo          TEXT,
  source_type   TEXT,
  source_id     BIGINT,
  /* A reversing entry points at the entry it reverses. The pair stays in the
     table together; neither is ever removed. */
  reverses_id   BIGINT,
  posted_by     TEXT,
  created_at    TEXT   NOT NULL,
  CONSTRAINT journal_entries_reverses_fkey FOREIGN KEY (reverses_id)
    REFERENCES journal_entries(id) ON DELETE RESTRICT,
  CONSTRAINT journal_entries_date_not_blank CHECK (length(trim(entry_date)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_journal_entries_date
  ON journal_entries(entry_date, id);
CREATE INDEX IF NOT EXISTS idx_journal_entries_source
  ON journal_entries(source_type, source_id);

/* ──────────────────────────── journal lines ────────────────────────────
   Exactly one of debit/credit is non-zero per line. Allowing both would let a
   single line net to zero while looking like it did something, and allowing
   neither would let an entry carry meaningless rows that still balance. */

CREATE TABLE IF NOT EXISTS journal_lines(
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_id    BIGINT NOT NULL,
  account_id  BIGINT NOT NULL,
  debit       NUMERIC(14, 2) NOT NULL DEFAULT 0,
  credit      NUMERIC(14, 2) NOT NULL DEFAULT 0,
  description TEXT,
  CONSTRAINT journal_lines_entry_fkey FOREIGN KEY (entry_id)
    REFERENCES journal_entries(id) ON DELETE CASCADE,
  CONSTRAINT journal_lines_account_fkey FOREIGN KEY (account_id)
    REFERENCES accounts(id) ON DELETE RESTRICT,
  CONSTRAINT journal_lines_one_side
    CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0)),
  CONSTRAINT journal_lines_non_negative CHECK (debit >= 0 AND credit >= 0)
);

CREATE INDEX IF NOT EXISTS idx_journal_lines_entry ON journal_lines(entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_account ON journal_lines(account_id);

/* ─────────────── the guard: this ledger cannot be rewritten ───────────────
   A rule, not a role grant. REVOKE needs a role model this deployment does not
   have (the app connects as the table owner), and a trigger still fires for
   the owner — which is the point: the API, a repair script and a human in psql
   are all refused by the same mechanism.

   DELETE is refused here too. journal_lines cascades from journal_entries, so
   deleting an entry would take its lines with it; the cascade is retained for
   the rollback path but no ordinary delete can reach it because deleting the
   entry is refused by its own rule below. */

CREATE OR REPLACE FUNCTION journal_lines_are_immutable()
RETURNS TRIGGER AS $$
BEGIN
  RAISE EXCEPTION
    'journal lines are immutable: post a reversing entry instead of editing or deleting one';
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
     WHERE tgname = 'trg_journal_lines_no_update' AND NOT tgisinternal
  ) THEN
    CREATE TRIGGER trg_journal_lines_no_update
      BEFORE UPDATE OR DELETE ON journal_lines
      FOR EACH ROW EXECUTE FUNCTION journal_lines_are_immutable();
  END IF;
END $$;

/* An entry's financial identity is its lines. Its header (memo, posted_by) may
   be corrected; its date and source may not, because changing either moves the
   entry to a different period, which is a different fact. */
CREATE OR REPLACE FUNCTION journal_entries_header_is_stable()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.entry_date IS DISTINCT FROM OLD.entry_date THEN
    RAISE EXCEPTION 'an entry date cannot be changed: post a reversal dated correctly instead';
  END IF;
  IF NEW.source_type IS DISTINCT FROM OLD.source_type OR NEW.source_id IS DISTINCT FROM OLD.source_id THEN
    RAISE EXCEPTION 'the source of an entry cannot be reassigned';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
     WHERE tgname = 'trg_journal_entries_stable' AND NOT tgisinternal
  ) THEN
    CREATE TRIGGER trg_journal_entries_stable
      BEFORE UPDATE ON journal_entries
      FOR EACH ROW EXECUTE FUNCTION journal_entries_header_is_stable();
  END IF;
END $$;

/* ────────────────── balance enforcement, at commit time ──────────────────
   Debits must equal credits for every entry. The obvious place is the route,
   and the route does check it — but a constraint that lives only in application
   code is not a constraint. A deferred constraint trigger checks at COMMIT, so
   a multi-statement entry can be built line by line and still be refused if it
   does not balance.

   It is deferred because a single INSERT of the first line is, transiently,
   unbalanced, and a per-statement check would make it impossible to write a
   correct entry at all. */

CREATE OR REPLACE FUNCTION journal_entry_must_balance()
RETURNS TRIGGER AS $$
DECLARE
  d NUMERIC(14, 2);
  c NUMERIC(14, 2);
  target BIGINT;
BEGIN
  target := COALESCE(NEW.entry_id, OLD.entry_id);
  SELECT COALESCE(SUM(debit), 0), COALESCE(SUM(credit), 0) INTO d, c
    FROM journal_lines WHERE entry_id = target;
  IF d <> c THEN
    RAISE EXCEPTION
      'entry % does not balance: debits % vs credits %', target, d, c;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
     WHERE tgname = 'trg_journal_entry_balanced' AND NOT tgisinternal
  ) THEN
    CREATE CONSTRAINT TRIGGER trg_journal_entry_balanced
      AFTER INSERT OR UPDATE ON journal_lines
      DEFERRABLE INITIALLY DEFERRED
      FOR EACH ROW EXECUTE FUNCTION journal_entry_must_balance();
  END IF;
END $$;

/* ───────────────────────────── credit notes ─────────────────────────────
   A credit note reduces what a customer owes. It is a document (quantity,
   reason, tax) and it posts its own journal entry; it is NOT a negative
   invoice, because the two are counted differently in reporting and a
   cancelled sale and a discounted one are different facts. */

CREATE TABLE IF NOT EXISTS credit_notes(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref           TEXT   NOT NULL UNIQUE,
  invoice_id    BIGINT,
  customer      TEXT   NOT NULL,
  reason        TEXT,
  subtotal      NUMERIC(14, 2) NOT NULL DEFAULT 0,
  tax           NUMERIC(14, 2) NOT NULL DEFAULT 0,
  total         NUMERIC(14, 2) NOT NULL DEFAULT 0,
  status        TEXT   NOT NULL DEFAULT 'draft',
  issued_at     TEXT,
  applied_at    TEXT,
  journal_entry_id BIGINT,
  note          TEXT,
  created_at    TEXT   NOT NULL,
  updated_at    TEXT   NOT NULL,
  CONSTRAINT credit_notes_invoice_fkey FOREIGN KEY (invoice_id)
    REFERENCES invoices(id) ON DELETE RESTRICT,
  CONSTRAINT credit_notes_journal_fkey FOREIGN KEY (journal_entry_id)
    REFERENCES journal_entries(id) ON DELETE RESTRICT,
  CONSTRAINT credit_notes_status_known
    CHECK (status IN ('draft','issued','applied','cancelled')),
  CONSTRAINT credit_notes_total_non_negative CHECK (total >= 0),
  CONSTRAINT credit_notes_customer_not_blank CHECK (length(trim(customer)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_credit_notes_invoice ON credit_notes(invoice_id);
CREATE INDEX IF NOT EXISTS idx_credit_notes_status ON credit_notes(status, created_at DESC);

/* ─────────────────────────────── expenses ───────────────────────────────
   Money out that is not a supplier invoice: rent, salaries, fuel, tools. A
   supplier invoice is a document matching an order and a receipt; an expense
   has no counterparty document to match and would fail every three-way check
   if forced through that table. */

CREATE TABLE IF NOT EXISTS expenses(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref           TEXT   NOT NULL UNIQUE,
  category      TEXT   NOT NULL,
  payee         TEXT,
  amount        NUMERIC(14, 2) NOT NULL,
  tax_amount    NUMERIC(14, 2) NOT NULL DEFAULT 0,
  spent_at      TEXT   NOT NULL,
  method        TEXT,
  reference     TEXT,
  account_id    BIGINT,
  journal_entry_id BIGINT,
  note          TEXT,
  created_by    TEXT,
  created_at    TEXT   NOT NULL,
  updated_at    TEXT   NOT NULL,
  CONSTRAINT expenses_account_fkey FOREIGN KEY (account_id)
    REFERENCES accounts(id) ON DELETE RESTRICT,
  CONSTRAINT expenses_journal_fkey FOREIGN KEY (journal_entry_id)
    REFERENCES journal_entries(id) ON DELETE RESTRICT,
  CONSTRAINT expenses_amount_positive CHECK (amount > 0),
  CONSTRAINT expenses_tax_non_negative CHECK (tax_amount >= 0),
  CONSTRAINT expenses_category_not_blank CHECK (length(trim(category)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_expenses_spent ON expenses(spent_at DESC);
CREATE INDEX IF NOT EXISTS idx_expenses_category ON expenses(category, spent_at DESC);

/* ────────────────────────────── tax records ──────────────────────────────
   Sales tax and withholding, as recorded at the moment a document was issued.
   Not derived on read: rates change, and a report that recomputes last year's
   tax at this year's rate is wrong in a way nobody notices until an audit. */

CREATE TABLE IF NOT EXISTS tax_records(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  /* sales | purchase | withholding */
  kind          TEXT   NOT NULL,
  source_type   TEXT   NOT NULL,
  source_id     BIGINT,
  tax_period    TEXT   NOT NULL,
  rate          NUMERIC(6, 4) NOT NULL DEFAULT 0,
  taxable_base  NUMERIC(14, 2) NOT NULL DEFAULT 0,
  tax_amount    NUMERIC(14, 2) NOT NULL DEFAULT 0,
  created_at    TEXT   NOT NULL,
  CONSTRAINT tax_records_kind_known CHECK (kind IN ('sales','purchase','withholding')),
  CONSTRAINT tax_records_period_format CHECK (tax_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT tax_records_rate_range CHECK (rate >= 0 AND rate <= 1),
  CONSTRAINT tax_records_amounts_non_negative CHECK (taxable_base >= 0 AND tax_amount >= 0)
);

CREATE INDEX IF NOT EXISTS idx_tax_records_period ON tax_records(tax_period, kind);

/* ─────────────────────────── payment schedules ───────────────────────────
   What is due when. An invoice with three instalments currently has one `due`
   date and a paid total, so "which instalment is late" cannot be answered.
   Each row is a promise; `paid` on the parent remains the cache of what has
   actually arrived. */

CREATE TABLE IF NOT EXISTS payment_schedules(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id    BIGINT NOT NULL,
  seq           INTEGER NOT NULL,
  due_date      TEXT   NOT NULL,
  amount        NUMERIC(14, 2) NOT NULL,
  paid          NUMERIC(14, 2) NOT NULL DEFAULT 0,
  status        TEXT   NOT NULL DEFAULT 'pending',
  note          TEXT,
  created_at    TEXT   NOT NULL,
  updated_at    TEXT   NOT NULL,
  CONSTRAINT payment_schedules_invoice_fkey FOREIGN KEY (invoice_id)
    REFERENCES invoices(id) ON DELETE CASCADE,
  CONSTRAINT payment_schedules_status_known
    CHECK (status IN ('pending','paid','waived')),
  CONSTRAINT payment_schedules_amount_positive CHECK (amount > 0),
  CONSTRAINT payment_schedules_paid_non_negative CHECK (paid >= 0),
  CONSTRAINT payment_schedules_seq_positive CHECK (seq > 0),
  CONSTRAINT payment_schedules_uniq UNIQUE (invoice_id, seq)
);

CREATE INDEX IF NOT EXISTS idx_payment_schedules_due ON payment_schedules(due_date, status);

