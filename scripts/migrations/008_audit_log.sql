-- 008 · platform audit log
--
-- Until now the word "audit" appeared 26 times in the API and never once meant
-- an audit trail. It was a JSON array embedded on individual quotes and tasks,
-- carrying whatever the route that wrote it decided to keep. There was no
-- platform-wide answer to "who changed this invoice, and when", which means
-- there was no answer at all to it for anything else.
--
-- That is not a nice-to-have. Every financially sensitive action in this system
-- — recording a payment, closing a return, adjusting stock, voiding an invoice,
-- changing a role — currently leaves no attributable record. An incident review
-- would consist of guessing from `updated_at` timestamps.
--
-- Design:
--
--   * APPEND-ONLY. There is no UPDATE and no DELETE path in the application,
--     and scripts/test-audit-log.mjs fails if one is ever added. A log you can
--     edit is evidence, not proof. Corrections are new rows.
--
--   * `before` and `after` are JSON snapshots, nullable. A creation has no
--     before; a deletion has no after. Both are stored as text so the row
--     survives even if the referenced entity does not — an audit row that
--     cascades away with the thing it describes is useless.
--
--   * NO FOREIGN KEY to users. The actor may be deleted, renamed, or be an
--     anonymous visitor. `actor_email` and `actor_name` are copied at write
--     time precisely so the record stays readable after the account is gone.
--     A FK here would either block account deletion or blank the actor.
--
--   * `action` is dotted `<entity>.<verb>` and the CHECK enforces that shape.
--     The vocabulary is deliberately open — new modules add verbs without a
--     migration — but a malformed action (no dot) is rejected, because that is
--     how a typo becomes an unfilterable row nobody finds again.
--
--   * No retention policy yet. Rows are small (a few hundred bytes) and the
--     alternative — deleting audit history on a schedule nobody configured —
--     is worse than growth. Revisit when volume justifies it.

CREATE TABLE IF NOT EXISTS audit_logs(
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id     BIGINT,
  actor_email  TEXT,
  actor_name   TEXT,
  actor_role   TEXT,
  action       TEXT   NOT NULL,
  entity_type  TEXT   NOT NULL,
  entity_id    TEXT,
  before_json  TEXT,
  after_json   TEXT,
  ip           TEXT,
  created_at   TEXT   NOT NULL,
  CONSTRAINT audit_logs_action_dotted     CHECK (action LIKE '%.%'),
  CONSTRAINT audit_logs_action_nonempty   CHECK (length(action) > 2),
  CONSTRAINT audit_logs_entity_nonempty   CHECK (length(entity_type) > 0)
);

-- The two queries that will actually be run: "history of this record" and
-- "everything this actor did, newest first".
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON audit_logs(entity_type, entity_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_actor  ON audit_logs(actor_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action ON audit_logs(action, id DESC);
