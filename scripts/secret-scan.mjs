#!/usr/bin/env node
/**
 * Woodex pre-commit/CI secret scan (PRD §18/§25 — standing rule after Phase-0 findings).
 *
 *   node scripts/secret-scan.mjs              # scan the working tree
 *   node scripts/secret-scan.mjs --self-test  # only prove the rules still fire
 *
 * Exit 1 on a hit. Values are never printed — only the file, the line and the
 * rule, so the scan's own output can be pasted into a pull request safely.
 *
 * WHAT CHANGED, AND WHY (Furniture 2030 Phase 1, finding F-01)
 *
 * This scan used to look for token SHAPES only (a Stripe key, a JWT, a private
 * key block). A sign-in written as a sentence — an e-mail address and a
 * password in a Markdown list — has no shape, so a document could carry one
 * with this scan green on every run. Two gaps:
 *
 *   1. PROSE CREDENTIALS. Four rules now cover the ways a credential gets
 *      written down by a person rather than generated by a service: an
 *      e-mail/password pair, a labelled password, an environment assignment
 *      with a real-looking value, and a connection string carrying a password.
 *      They run on documentation and configuration files; the connection-string
 *      rule runs everywhere.
 *
 *   2. THE WORKING TREE. The old scan read each file from HEAD, which is the
 *      one version that is already committed. Run before a commit, it could
 *      not see the change being committed, and it never saw a new file at all.
 *      It now reads the files on disk: everything tracked plus everything
 *      untracked that .gitignore does not exclude.
 *
 * Demo sign-ins are deliberately public (they exist only on a local database
 * and the server refuses to create them in production), so their values are
 * listed in DEMO_VALUES rather than flagged. That list is the only place to
 * add one, and each entry says where it is documented.
 *
 * WHAT THIS STILL DOES NOT DO: it does not read Git history. A secret that was
 * committed and later removed is still in the history and must be rotated.
 * Removal from the current files is hygiene, not a fix.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";

const TOKEN_PATTERNS = [
  [/sk_live_[A-Za-z0-9]{8,}/, "Stripe live key"],
  [/sk_test_[A-Za-z0-9]{8,}/, "Stripe test key"],
  [/sbp_[A-Za-z0-9_\-]{16,}/, "Supabase PAT"],
  [/eyJ[A-Za-z0-9_\-]{20,}\.[A-Za-z0-9_\-]{10,}\.?[A-Za-z0-9_\-]*/, "JWT-shaped token"],
  [/["']?service_role["']?\s*[:=]\s*["'][^"']{20,}/, "Supabase service_role key"],
  [/AWS_SECRET_ACCESS_KEY\s*=\s*[A-Za-z0-9/+=]{20,}/, "AWS secret"],
  [/xox[baprs]-[A-Za-z0-9-]{10,}/, "Slack token"],
  [/-----BEGIN (RSA |EC |OPENSSH |)PRIVATE KEY-----/, "private key block"],
];

/* Files that describe findings rather than carry them. */
const ALLOW = new Set(["docs/audits/PHASE0-AUDIT-REPORT-2026-10-05.md", "scripts/secret-scan.mjs"]);

/* Demo sign-ins that are public on purpose. Never a production value. */
const DEMO_VALUES = new Set([
  "admin",        // local owner login — AGENTS.md, README.md; never created when NODE_ENV=production
  "woodex123",    // local demo team (editor / sales / finance / viewer) — same guard
  "woodex-demo",  // retired mock gate, described in docs/archive/AGENCY-OS-MASTER-PLAN-v3.md
  "woodex-admin", // another project's demo gate, quoted in docs/audits/REIMAGINED-COMPARISON-2026-11-08.md
]);

/* A value that is visibly a stand-in, not a secret. */
const PLACEHOLDER = /^(?:x{3,}|\*{2,}|\.{2,}|…+|<.*>?|\[.*\]?|\{.*\}?|\$.*|%.*%|your[-_ a-z0-9]*|change[-_ ]?me|example[-_a-z0-9]*|placeholder|password|passwd|secret|redacted|masked|hidden|none|null|undefined|string|pw|pass|user|username|postgres|root|test|n\/a)$/i;
const isStandIn = (value) => {
  const v = String(value).trim().replace(/[.,;:!?)]+$/, "");
  return v.length < 3 || PLACEHOLDER.test(v) || DEMO_VALUES.has(v) || /\.{3}|…|<[^>]*>|\$\{|\$\(|process\.env/.test(v);
};

/* Prose rules. Each returns the candidate secret (or null) for one line. */
const PROSE_RULES = [
  { label: "e-mail and password written as a pair",
    re: /`([^`\s]+@[^`\s]+\.[^`\s]+)`\s*(?:\/|\||,|:|—|–|-|and|with)\s*`([^`\s]{3,})`/g,
    value: (m) => m[2] },
  { label: "labelled password",
    re: /\b(?:password|passphrase|passwd|pwd)\b[^\n`"']{0,12}?[:=]\s*\**\s*(?:`([^`\n]{4,})`|"([^"\n]{4,})"|'([^'\n]{4,})')/gi,
    value: (m) => m[1] ?? m[2] ?? m[3] },
  { label: "secret assigned in an environment example",
    re: /\b[A-Z0-9_]*(?:PASSWORD|PASSWD|SECRET|API_KEY|TOKEN|PRIVATE_KEY)[A-Z0-9_]*\s*=\s*["'`]?([^\s"'`]{4,})/g,
    value: (m) => m[1] },
];
const DSN_RULE = { label: "connection string carrying a password",
  re: /\b(?:postgres(?:ql)?|mysql|mariadb|mongodb(?:\+srv)?|redis|amqps?):\/\/([^\s:@/`"']+):([^\s@/`"']+)@([^\s/:`"')]+)/g,
  value: (m) => (/^(?:localhost|127\.0\.0\.1|host|hostname|db|example\.(?:com|org|net))$/i.test(m[3]) && isStandIn(m[2]) ? null : m[2]) };

const isBinary = (f) => /\.(jpe?g|png|webp|avif|gif|ico|woff2?|ttf|otf|eot|pdf|zip|gz|tgz|db|sqlite|mp4|webm|mp3)$/i.test(f);
const isProse = (f) => /\.(md|mdx|txt|ya?ml|json|html?|toml|ini|csv|example|sample)$/i.test(f) || /(^|\/)\.env[^/]*$/.test(f);

/** Scan one file's text. Returns [{ line, label }] — never the value. */
export function scanText(file, text) {
  const found = [];
  const jwtAllowed = /eyJ[A-Za-z0-9_\-]{20,}\.eyJ/.test(text) && (/\.md$|\.example|LICENSE/.test(file) || /anon|publishable/i.test(text));
  const prose = isProse(file);
  const lines = text.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const ln = lines[i];
    for (const [re, label] of TOKEN_PATTERNS) {
      if (label === "JWT-shaped token" && jwtAllowed) continue;
      if (re.test(ln)) { found.push({ line: i + 1, label }); break; }
    }
    const rules = prose ? [...PROSE_RULES, DSN_RULE] : [DSN_RULE];
    for (const rule of rules) {
      rule.re.lastIndex = 0;
      for (const m of ln.matchAll(rule.re)) {
        const value = rule.value(m);
        if (value !== null && value !== undefined && !isStandIn(value)) { found.push({ line: i + 1, label: rule.label }); break; }
      }
    }
  }
  return found;
}

/* The rules prove themselves on every run. A scan whose patterns have quietly
   stopped matching is worse than no scan, because it still prints a green tick.
   Samples are assembled at runtime so this file holds no literal that looks
   like a credential. */
function selfTest() {
  const j = (...parts) => parts.join("");
  const mustFlag = [
    ["docs/x.md", j("- **Production:** `owner@", "example.com` / `Xy7Qq2", "Lm9Tz`"), "e-mail and password written as a pair"],
    ["docs/x.md", j("| owner | `ops@", "example.org` | `Wd-2030", "-Kq81` |"), "e-mail and password written as a pair"],
    ["docs/x.md", j("The admin pass", "word: `S3cure", "-Phrase-41`"), "labelled password"],
    ["docs/x.md", j("INITIAL_ADMIN_PASS", "WORD=Abc12345", "xyzQ"), "secret assigned in an environment example"],
    [".env.example", j("SMTP_PASS", "WORD=", "hunter2hunter2"), "secret assigned in an environment example"],
    ["scripts/x.mjs", j("const url = \"postgres://app:Re4l", "Pw99zz@db.prod.example.io:5432/app\";"), "connection string carrying a password"],
    ["docs/x.md", j("sk_", "live_", "abcdEFGH1234"), "Stripe live key"],
  ];
  const mustPass = [
    ["docs/x.md", "- **Local seed:** `admin@woodex.pk` / `admin` — never in production"],
    ["docs/x.md", "Demo team: `ayesha@woodex.pk` / `woodex123`"],
    ["docs/x.md", "password: `<choose a strong one>`"],
    ["docs/x.md", "INITIAL_ADMIN_PASSWORD=<set in the Vercel dashboard>"],
    ["docs/x.md", "INITIAL_ADMIN_PASSWORD=$(openssl rand -base64 24)"],
    ["scripts/x.mjs", "node scripts/pg-migrate.mjs --dsn postgres://user:pw@host:5432/db"],
    ["docs/x.md", "Done in the original QA pass: QA-01/02/03 plus QA-04/05."],
    ["docs/x.md", "A password change is the moment somebody believes their old password is known to someone else."],
    ["apps/x.ts", "const body = { email, password: form.password };"],
  ];
  const problems = [];
  for (const [file, text, label] of mustFlag) {
    if (!scanText(file, text).some((hit) => hit.label === label)) problems.push(`rule did not fire: ${label} (${file})`);
  }
  for (const [file, text] of mustPass) {
    const hits = scanText(file, text);
    if (hits.length) problems.push(`false alarm: "${text.slice(0, 48)}…" → ${hits[0].label}`);
  }
  return problems;
}

const selfProblems = selfTest();
if (selfProblems.length) {
  console.error("⛔ secret-scan: the scan's own rules are broken — nothing below can be trusted:");
  for (const p of selfProblems) console.error("   " + p);
  process.exit(2);
}
if (process.argv.includes("--self-test")) {
  console.log("✓ secret-scan rules fire on every sample and stay quiet on every documented demo value");
  process.exit(0);
}

let files = [];
try {
  files = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard"], { encoding: "utf8", maxBuffer: 64e6 })
    .split("\n").filter(Boolean);
} catch { console.error("not a git repo"); process.exit(2); }
files = [...new Set(files)];

const hits = [];
let scanned = 0;
for (const f of files) {
  if (ALLOW.has(f) || f.includes("node_modules") || isBinary(f)) continue;
  let text;
  try { text = fs.readFileSync(f, "utf8"); }
  catch { continue; } // deleted in the working tree, or not a regular file
  scanned += 1;
  for (const hit of scanText(f, text)) hits.push([f, hit.line, hit.label]);
}
if (hits.length) {
  console.error("⛔ secret-scan: credentials found in:");
  for (const [f, line, label] of hits) console.error(`   ${f}:${line} → ${label}`);
  console.error("   (values not printed) — remove it, CHANGE the credential (it stays in Git history), then retry.");
  console.error("   A documented demo value belongs in DEMO_VALUES in scripts/secret-scan.mjs, with where it is documented.");
  process.exit(1);
}
console.log(`✓ secret-scan clean (${scanned} files read from the working tree, ${files.length} listed; token and prose-credential rules)`);
